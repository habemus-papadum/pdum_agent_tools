import assert from 'node:assert/strict';
import {mkdir,writeFile}from'node:fs/promises';
import {query}from'@anthropic-ai/claude-agent-sdk/browser';
import {installFeedAdapter,openClient,until,connections}from'./client.mjs';
const base=process.env.SPIKE071_URL;
assert(base);const folder=new URL('../../artifacts/071-claude-sdk-replay/',import.meta.url);await mkdir(folder,{recursive:true});
const call=async(path,body)=>{const r=await fetch(base+path,{method:body===undefined?'GET':'POST',headers:{'Content-Type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});if(!r.ok)throw Error(`HTTP${r.status}`);return r.json();};
installFeedAdapter();
const run=await call('/sessions',{max_budget:.02,max_turns:1});const url=base.replace('http','ws')+run.feed;
let callbacks=0;const callbackIds=[];const clients=[];const checks=[];
const hooks={UserPromptSubmit:[{hooks:[async(_input,_id,options)=>{callbacks++;callbackIds.push(options);return {decision:'block',reason:'No-model SDK replay qualification'};}]}]};
try {
 const a=await openClient(query,url,{hooks});clients.push(a);
 const b=await openClient(query,url,{hooks});clients.push(b);
 await Promise.all([a.session.interrupt(),b.session.interrupt()]);
 checks.push({name:'Two official SDK clients control same native process',pass:true});
 a.send('This input must be blocked before inference.');await until(()=>a.messages.some(m=>m.type==='result'));
 const before=callbacks;assert(before>=2);
 checks.push({name:'Native hook invokes callbacks in both SDK clients',count:before});
 await a.close();await b.close();
 assert((await call('/sessions/'+run.id)).running);
 checks.push({name:'Closing SDK connections preserves process',pass:true});
 const c=await openClient(query,url,{hooks});clients.push(c);
 await until(()=>c.messages.some(m=>m.type==='result'));
 await new Promise(resolve=>setTimeout(resolve,100));
 checks.push({name:'Full replay invokes already-resolved historical hook again',callbacksAdded:callbacks-before,observed:callbacks>before});
 assert(callbacks>before);
 c.socket.socket.close(4001,'Injected connection loss');await c.completion;
 const socketCount=connections.length;await new Promise(resolve=>setTimeout(resolve,250));
 checks.push({name:'Abnormal socket close ends Query without native WebSocket reconnect',errors:c.errors,reconnected:connections.length!==socketCount});
 assert(connections.length===socketCount);
 await assert.rejects(c.session.interrupt());
 const beforeGuarded=callbacks;installFeedAdapter({passiveReplay:true});
 const d=await openClient(query,url,{hooks});clients.push(d);
 await until(()=>d.messages.some(m=>m.type==='result'));await d.session.interrupt();
 assert(callbacks===beforeGuarded);
 checks.push({name:'Client-side passive replay avoids resolved hook execution; fresh Query controls same process',pass:true});
 const raw=d.socket.nativeFrames.map(x=>x.frame);const results=raw.filter(m=>m.type==='result');
 assert(results.every(r=>r.total_cost_usd===0));
 const report={date:new Date().toISOString(),sdk:'0.3.296',native:'2.1.310',checks,modelCalls:0,costUsd:0,sessionId:run.id,pid:run.pid};
 await writeFile(new URL('no-model.json',folder),JSON.stringify(report,null,2));
 await writeFile(new URL('no-model-client-records.json',folder),JSON.stringify(clients.map(c=>({messages:c.messages,sent:c.socket.sent,raw:c.socket.nativeFrames,errors:c.errors})),null,2));
 console.log(JSON.stringify(report,null,2));
} finally {for(const client of clients)await client.close();console.log(JSON.stringify({cleanup:await call('/sessions/'+run.id+'/stop',{})}));}
