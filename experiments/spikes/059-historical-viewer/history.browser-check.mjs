/** Run inside the actual Vite page. Captures only counts/booleans, never native message bodies. */
export async function runHistoryBrowserChecks() {
  const checks = [];
  const check = (name, passed) => checks.push({name, passed: Boolean(passed)});
  const kit = window['__native-history'];
  const tick = () => new Promise(resolve => setTimeout(resolve, 80));
  const call = async (name, args) => {const result = await kit.call(name, args); await tick(); return result;};
  const report = () => kit.call('report', {format: 'full'});
  const set = (name, value) => call('set', {name: `native-history/${name}`, value});
  await set('provider', 'all'); await set('catalogQuery', ''); await set('inspector', 'provenance');
  let r = await report();
  check('five real scoped cells ready', r.cells.length === 5 && r.cells.every(cell => cell.state === 'ready'));
  check('real provider inventory present', r.history.catalog.some(entry => entry.provider === 'codex') && r.history.catalog.some(entry => entry.provider === 'claude'));
  check('inspection-only actions', r.actions.every(action => !/resume|start|fork|submit|delete|login/.test(action.name)));
  const codex = r.history.catalog.find(entry => entry.provider === 'codex');
  const claude = r.history.catalog.find(entry => entry.key === 'claude-586df0be-7a86-4cb9-9942-d3a5f8dd09df') ?? r.history.catalog.find(entry => entry.provider === 'claude');
  await call('open-history', {key: codex.key});
  r = await report();
  check('Codex raw history has native items and unknown accounting', r.history.items.length > 0 && r.history.usage.cost === null && r.history.usage.context === null);
  check('native provenance matches selected Codex session', document.querySelector('.history-provenance dd')?.textContent === codex.sessionId);
  const firstCodex = r.history.items[0];
  await call('jump', {id: firstCodex.id}); await set('inspector', 'raw');
  check('item raw record opens by native path', document.querySelector('.history-raw')?.textContent.includes(firstCodex.path));
  const nextCodex = r.history.items[1] ?? firstCodex;
  await call('jump', {id: nextCodex.id});
  check('raw inspector replaces the selected native record', document.querySelector('.history-raw')?.textContent.includes(nextCodex.path));
  await set('inspector', 'provenance'); await call('open-history', {key: claude.key});
  r = await report();
  check('source switch replaces provenance and transcript together', document.querySelector('.history-provenance dd')?.textContent === claude.sessionId && r.history.items.every(item => item.id.startsWith(claude.key)));
  check('Claude ledger uses native response IDs', r.history.usage.requests.length > 0 && r.history.usage.requests.every(row => row.id));
  await set('kind', 'tool');
  check('tool filter includes Claude tool_use and tool_result containers', document.querySelectorAll('.history-tool,.history-result').length >= 2);
  await set('query', 'no-match-059-test');
  check('transcript search affects visible items without changing the ledger', (await report()).history.visible === 0 && (await report()).history.usage.requests.length === r.history.usage.requests.length);
  await set('query', ''); await set('kind', 'all');
  await call('open-history', {key: '@specimen'});
  await new Promise(resolve => setTimeout(resolve, 700));
  check('synthetic bench is visibly separate', document.querySelector('.history-specimen-banner')?.textContent.includes('Nothing in this session is provider evidence'));
  check('real TeX components rendered inline and display forms', document.querySelectorAll('[data-tex]').length === 2);
  check('real Mermaid component rendered an SVG', document.querySelectorAll('[data-mermaid] svg').length > 0);
  check('code has language token color', document.querySelectorAll('.hljs-keyword').length > 0);
  check('image bytes decode', [...document.querySelectorAll('.history-image img')].some(img => img.complete && img.naturalWidth > 0));
  check('unknown native-shaped block remains visible', document.querySelector('.history-unknown')?.textContent.includes('future_provider_block'));
  await call('step-item', {direction: 'next'});
  check('navigation action moves the actual focused item', document.activeElement?.matches('[data-history-item]'));
  document.activeElement?.blur();
  document.body.dispatchEvent(new KeyboardEvent('keydown', {key: ' ', bubbles: true})); await tick();
  check('Space opens shared keyboard palette', !!document.querySelector('.command-map'));
  document.body.dispatchEvent(new KeyboardEvent('keydown', {key: 'Escape', bubbles: true})); await tick();
  check('Escape closes shared keyboard palette', !document.querySelector('.command-map'));
  check('no page overflow', document.documentElement.scrollWidth <= innerWidth + 1);
  check('no page fault', !document.querySelector('.aiui-page-fault'));
  r = await report();
  check('source stamped controls and cells', r.controls.every(control => control.loc) && r.cells.every(cell => cell.loc));
  await call('open-history', {key: claude.key});
  return {passed: checks.filter(check => check.passed).length, total: checks.length, allPassed: checks.every(check => check.passed), viewport: [innerWidth, innerHeight], checks};
}
