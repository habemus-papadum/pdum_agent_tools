import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { appendFileSync, copyFileSync, readFileSync, rmSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
import { digest, Run } from './harness.mjs';

const corpusPath = resolve(process.argv[2] ?? '');
assert(process.argv.includes('--live-cli'), 'Pass corpus artifact directory and --live-cli (one Luna CLI turn)');
const corpus = JSON.parse(readFileSync(join(corpusPath, 'corpus.json')));
const run = new Run('026-codex-session-admin', { isolated: corpus.metadata.isolated });
const result = { metadata: run.metadata, corpus: corpusPath, cases: {}, source: corpus.histories.paginated.threadId };
const deadline = setTimeout(() => run.process?.kill('SIGTERM'), 120_000);
let cli;
let copiedAuth;
let sourceAuth;
let sourceAuthHash;
try {
  let a = await run.start();
  const b = await run.connect('B');
  const record = async (label, method, params, client = a) => result.cases[label] = await client.rpc(method, params);
  const fork1 = await a.ok('thread/fork', { threadId: result.source, excludeTurns: true });
  const fork2 = await b.ok('thread/fork', { threadId: result.source, excludeTurns: true, cwd: corpus.histories.legacy.work });
  result.ids = [result.source, corpus.histories.legacy.threadId, fork1.thread.id, fork2.thread.id];
  await a.ok('thread/name/set', { threadId: fork1.thread.id, name: 'ADMIN_ALPHA' });
  await b.ok('thread/name/set', { threadId: fork2.thread.id, name: 'ADMIN_BETA' });
  await record('listDefaults', 'thread/list', {});
  await record('listAllSources', 'thread/list', { sourceKinds: ['cli', 'vscode', 'exec', 'appServer', 'subAgent', 'unknown'], modelProviders: [] });
  await record('searchName', 'thread/list', { searchTerm: 'ADMIN_ALPHA' });
  await record('searchContent', 'thread/list', { searchTerm: 'HISTORY_STDERR' });
  await record('searchPrompt', 'thread/list', { searchTerm: 'Bounded history research' });
  await record('cwdFilter', 'thread/list', { cwd: corpus.histories.legacy.work });
  await record('providerEmpty', 'thread/list', { modelProviders: [] });
  await record('providerWrong', 'thread/list', { modelProviders: ['nonexistent'] });
  const page = await record('page1', 'thread/list', { limit: 2, sortDirection: 'asc' });
  await a.ok('thread/name/set', { threadId: fork1.thread.id, name: 'ADMIN_ALPHA_UPDATED' });
  if (page.result?.nextCursor) await record('page2AfterRename', 'thread/list', { limit: 2, sortDirection: 'asc', cursor: page.result.nextCursor });
  if (page.result?.backwardsCursor) await record('reverse', 'thread/list', { limit: 2, sortDirection: 'desc', cursor: page.result.backwardsCursor });
  await record('parentArchive', 'thread/archive', { threadId: result.source });
  await record('listAfterParentArchive', 'thread/list', {});
  await record('listArchived', 'thread/list', { archived: true });
  await record('archivedHistory', 'thread/read', { threadId: result.source, includeTurns: true });
  await record('parentUnarchive', 'thread/unarchive', { threadId: result.source });
  await record('deleteFork', 'thread/delete', { threadId: fork2.thread.id });
  await record('sourceAfterForkDelete', 'thread/read', { threadId: result.source, includeTurns: true });
  result.notificationsB = run.events.filter(x => x.connection === 'B' && x.direction === 'server' && x.message.method).map(x => x.message);
  await run.stop();
  // Sequential CLI access: no competing writer, no normal-profile writes.
  run.phase = 'vanilla-cli';
  copiedAuth = join(run.codexHome, 'auth.json');
  sourceAuth = join(process.env.CODEX_HOME ?? join(process.env.HOME, '.codex'), 'auth.json');
  sourceAuthHash = digest(readFileSync(sourceAuth));
  copyFileSync(sourceAuth, copiedAuth);
  const args = ['exec', '--json', '--skip-git-repo-check', '--dangerously-bypass-approvals-and-sandbox', '--model', 'gpt-6-luna', '-c', 'model_reasoning_effort="low"', '-c', 'web_search="disabled"', '-c', 'features.apps=false', '-c', 'features.plugins=false', '-c', 'skills.bundled.enabled=false', 'Do not use tools. Reply with exactly CLI_CATALOGUE_OK.'];
  run.save('cli-invocation.json', { binary: run.binary, args, cwd: run.work, boundedSeconds: 45, requestedModel: 'gpt-6-luna' });
  cli = spawn(run.binary, args, { cwd: run.work, env: run.env, stdio: ['ignore', 'pipe', 'pipe'] });
  const timer = setTimeout(() => cli.kill('SIGTERM'), 45_000);
  cli.stdout.on('data', chunk => appendFileSync(join(run.artifacts, 'cli.jsonl'), chunk));
  cli.stderr.on('data', chunk => appendFileSync(join(run.artifacts, 'cli-stderr.log'), chunk));
  result.cliExit = await new Promise(resolve => cli.once('close', resolve));
  clearTimeout(timer);
  rmSync(copiedAuth, { force: true });
  assert.equal(result.cliExit, 0);
  run.phase = 'post-cli';
  a = await run.start();
  await record('restartDefaults', 'thread/list', {});
  await record('restartExec', 'thread/list', { sourceKinds: ['exec'] });
  await record('restartCli', 'thread/list', { sourceKinds: ['cli'] });
  await record('restartAll', 'thread/list', { sourceKinds: ['cli', 'vscode', 'exec', 'appServer', 'subAgent', 'unknown'], modelProviders: [] });
  await delay(50);
  result.passed = true;
} catch (error) { result.error = error.stack; result.passed = false; }
finally {
  clearTimeout(deadline);
  if (cli?.exitCode === null) cli.kill('SIGTERM');
  if (copiedAuth) rmSync(copiedAuth, { force: true });
  if (sourceAuthHash) result.sourceAuthUnchanged = digest(readFileSync(sourceAuth)) === sourceAuthHash;
  await run.stop();
  run.save('result.json', result);
}
console.log(JSON.stringify({ passed: result.passed, artifacts: run.artifacts, error: result.error }));
if (!result.passed) process.exitCode = 1;
